import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const java=readFileSync(new URL('../app/src/main/java/fr/roadguard/app/RadarViewport.java',import.meta.url),'utf8');
const field=name=>JSON.parse(java.match(new RegExp('static final String '+name+' = (".*");'))[1]);
const query=field('QUERY'),install=field('INSTALL');
const point=(lat,lng)=>({lat,lng});
const bounds={getCenter:()=>point(46.75,6.1),getNorthEast:()=>point(46.8,6.2)};
const map={getBounds:()=>bounds};
const libre=vm.runInNewContext(query,{map});assert.equal(libre[0],46.75);assert.equal(libre[1],6.1);assert.ok(libre[2]>5000&&libre[2]<20000);
const leaflet=vm.runInNewContext(query,{map:{getBounds:()=>({...bounds,pad:()=>{throw Error('must not depend on Leaflet padding')}})}});assert.deepEqual(Array.from(leaflet),Array.from(libre));
assert.equal(vm.runInNewContext(query,{}),null);
assert.equal(vm.runInNewContext(query,{map:{getBounds:()=>({getCenter:()=>point(NaN,6),getNorthEast:()=>point(46,7)})}}),null);
const canvas=vm.runInNewContext(query,{minLat:46,maxLat:48,minLon:5,maxLon:7,scale:2,panX:100,panY:200,innerWidth:1000,innerHeight:1000});assert.equal(canvas[0],47.2);assert.equal(canvas[1],5.9);assert.equal(canvas[2],60000);
let refresh=0,callbacks={},pending,registered=0;const window={RoadguardMap:{refreshRadars:()=>refresh++}};
const context={window,map:{...map,on:(name,fn)=>{callbacks[name]=fn;registered++;}},setTimeout:fn=>{pending=fn;return 1;},clearTimeout:()=>{pending=null;}};
vm.runInNewContext(install,context);vm.runInNewContext(install,context);assert.equal(registered,2);callbacks.moveend();callbacks.zoomend();assert.equal(refresh,0);pending();assert.equal(refresh,1);
let added=0;vm.runInNewContext(install,{window:{},map:{getBounds:()=>({...bounds,pad(){}}),on:()=>added++}});assert.equal(added,0);
console.log('Radar viewport: MapLibre, Leaflet, canvas, invalid bounds and debounced refresh passed');
